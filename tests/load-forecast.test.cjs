const badtime=JSON.parse(JSON.stringify(B));badtime.models.PatchTST.days['2025-11-02'].timestamps[1]=badtime.models.PatchTST.days['2025-11-02'].timestamps[0];
assert.throws(()=>A.adapt(badtime,'PatchTST','2025-11-02'));
const schema=JSON.parse(JSON.stringify(B));schema.interval_minutes=60;
assert.throws(()=>A.adapt(schema,'PatchTST','2025-11-02'));
// Restore preserves original demo path and gates.
